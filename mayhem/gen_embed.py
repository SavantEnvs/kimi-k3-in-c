#!/usr/bin/env python3
"""Write a C header embedding files as byte arrays: gen_embed.py OUT NAME=PATH ..."""
import sys

out, pairs = sys.argv[1], sys.argv[2:]
with open(out + ".tmp", "w") as f:
    f.write("/* generated by mayhem/gen_embed.py from committed fixtures; do not edit */\n")
    f.write("#pragma once\n")
    for pair in pairs:
        name, path = pair.split("=", 1)
        data = open(path, "rb").read()
        f.write("static const unsigned char %s[%d] = {\n" % (name, max(len(data), 1)))
        for i in range(0, len(data), 16):
            f.write("  " + ",".join(str(b) for b in data[i:i + 16]) + ",\n")
        if not data:
            f.write("  0\n")
        f.write("};\n")
import os
os.replace(out + ".tmp", out)
